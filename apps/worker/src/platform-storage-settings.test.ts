import { createHash, randomBytes } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { PrismaClient } from "@xhs-agentic/database";
import { createObjectStorage, LocalObjectStorage } from "@xhs-agentic/object-storage";
import { afterEach, describe, expect, it, vi } from "vitest";
import { loadWorkerPlatformSettings } from "./platform-settings";

const s3Environment = {
  OBJECT_STORAGE_ACCESS_KEY: "worker-storage-fixture",
  OBJECT_STORAGE_SECRET_KEY: "worker-storage-fixture-secret",
  OBJECT_STORAGE_BUCKET: "worker-storage-fixture",
  OBJECT_STORAGE_REGION: "us-east-1",
  OBJECT_STORAGE_ENDPOINT: "https://storage.example.test",
};
function database(provider?: string) {
  return {
    platformSetting: {
      findMany: vi
        .fn()
        .mockResolvedValue(provider ? [{ key: "storage.provider", value: provider }] : []),
    },
  } as unknown as PrismaClient;
}
afterEach(() => vi.unstubAllEnvs());

describe("Worker local and S3 storage selection", () => {
  it("loads LOCAL from the database without any S3 credentials and shares persisted API objects", async () => {
    const directory = await mkdtemp(join(tmpdir(), "qisheng-worker-storage-"));
    try {
      for (const name of Object.keys(s3Environment)) vi.stubEnv(name, undefined);
      vi.stubEnv("OBJECT_STORAGE_PROVIDER", "S3");
      vi.stubEnv("OBJECT_STORAGE_LOCAL_ROOT", directory);
      vi.stubEnv("ADMIN_JWT_SECRET", randomBytes(32).toString("base64"));
      const settings = await loadWorkerPlatformSettings(database("LOCAL"));
      expect(settings.storage.provider).toBe("LOCAL");
      const worker = createObjectStorage(settings.storage);
      expect(worker).toBeInstanceOf(LocalObjectStorage);
      await worker.ensureBucket(false);
      const bytes = Buffer.from("worker generated bytes");
      const checksum = createHash("sha256").update(bytes).digest("hex");
      const key = "tenants/fixture/campaigns/generated/image.png";
      await worker.put({ key, bytes, checksum, mimeType: "image/png" });
      const anotherProcess = createObjectStorage(settings.storage);
      expect(Buffer.from(await anotherProcess.get(key))).toEqual(bytes);
      expect(await anotherProcess.head(key)).toMatchObject({ checksum, byteSize: bytes.length });
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });

  it.each([undefined, "S3"])(
    "preserves existing S3 configuration with provider=%s",
    async (provider) => {
      vi.stubEnv("OBJECT_STORAGE_PROVIDER", "");
      for (const [key, value] of Object.entries(s3Environment)) vi.stubEnv(key, value);
      const settings = await loadWorkerPlatformSettings(database(provider));
      expect(settings.storage).toMatchObject({
        provider: "S3",
        bucket: s3Environment.OBJECT_STORAGE_BUCKET,
        accessKeyId: s3Environment.OBJECT_STORAGE_ACCESS_KEY,
        region: "us-east-1",
      });
    },
  );

  it("rejects unknown providers instead of silently selecting another backend", async () => {
    await expect(loadWorkerPlatformSettings(database("OTHER"))).rejects.toThrow(
      "storage.provider is invalid",
    );
  });

  it("loads material settings independently of an unavailable audit model without bypassing storage validation", async () => {
    for (const [key, value] of Object.entries(s3Environment)) vi.stubEnv(key, value);
    vi.stubEnv("OBJECT_STORAGE_PROVIDER", "S3");
    vi.stubEnv("CONTENT_SAFETY_MODE", "MODEL");
    vi.stubEnv("CONTENT_SAFETY_MODEL_PROVIDER_ID", "unavailable-audit-provider");
    const prisma = database("S3");
    const provider = vi.fn().mockResolvedValue({ status: "DISABLED" });
    Object.assign(prisma, { modelProvider: { findUnique: provider } });
    await expect(loadWorkerPlatformSettings(prisma)).rejects.toThrow(
      "Content-safety model provider is unavailable",
    );
    provider.mockClear();
    const settings = await loadWorkerPlatformSettings(prisma, { contentSafety: false });
    expect(provider).not.toHaveBeenCalled();
    expect(settings.storage).toMatchObject({
      provider: "S3",
      bucket: s3Environment.OBJECT_STORAGE_BUCKET,
    });
    await expect(
      loadWorkerPlatformSettings(database("OTHER"), { contentSafety: false }),
    ).rejects.toThrow("storage.provider is invalid");
  });

  it("requires a signing secret for LOCAL and still requires credentials for S3", async () => {
    vi.stubEnv("ADMIN_JWT_SECRET", undefined);
    await expect(loadWorkerPlatformSettings(database("LOCAL"))).rejects.toThrow();
    vi.stubEnv("OBJECT_STORAGE_ACCESS_KEY", undefined);
    await expect(loadWorkerPlatformSettings(database("S3"))).rejects.toThrow(
      "OBJECT_STORAGE_ACCESS_KEY",
    );
  });
});
